test('Demo PBL automatically activates a failed target and exhausts after the second cycle', async ({ page }) => {
  await page.goto('/')
  await page.locator('.role-button.student').click()
  await expect(page.locator('[aria-label="当前课堂上下文"]')).toBeVisible()
  const question = page.locator('textarea').first()
  for (const [answer, phase] of [
    ['局部红肿涉及血管反应，我先明确需要解释的问题。', '提出假设'],
    ['我假设血流增加与通透性升高共同导致红肿，但仍不确定。', '讨论证据'],
    ['血管扩张支持红，渗出支持肿，但需要考虑证据限制。', '总结解释'],
    ['综合机制与证据后保留疑问，需要再核对通透性变化。', '已完成'],
  ] as const) {
    const submit = page.locator('.composer uni-button')
    await question.fill(answer)
    await expect(submit).not.toHaveAttribute('disabled')
    await submit.click()
    await expect(page.getByText(`我的阶段：${phase}`, { exact: true })).toBeVisible()
    if (phase !== '已完成') await expect(question).toHaveValue('')
  }
  await page.locator('.student-nav__item').filter({ hasText: '学情' }).click()
  await expect(page.getByText('当前重点', { exact: true })).toBeVisible()
  await expect(page.getByText('待发布学习', { exact: true }).first()).toBeVisible()
  await page.locator('.report-row').first().click()
  await expect(page.getByText('四阶段讨论证据', { exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByText('当前重点', { exact: true })).toBeVisible()
  await page.locator('.student-nav__item').filter({ hasText: '答疑' }).click()
  await page.getByText('退出', { exact: true }).click()

  await page.locator('.role-button.teacher').click()
  await expect(page.getByText('诊断待办', { exact: true })).toBeVisible()
  await page.getByText('采用并发布', { exact: true }).click()
  await expect(page.locator('.suggestion uni-button').filter({ hasText: '已发布' })).toBeVisible()
  await page.getByText('退出', { exact: true }).click()

  await page.locator('.role-button.student').click()
  await page.locator('.student-nav__item').filter({ hasText: '学习' }).click()
  for (let step = 0; step < 3; step += 1) {
    const task = page.locator('.task--next')
    await expect(task).toBeVisible()
    const title = await task.locator('.subtitle').innerText()
    if (title.includes('正式讨论题')) await task.locator('textarea').fill('提交首轮证据链。')
    else if (title.includes('知识巩固')) await task.locator('uni-label').nth(0).click()
    else await task.locator('uni-label').nth(1).click()
    await expect(task.locator('uni-button.primary')).not.toHaveAttribute('disabled')
    await task.getByText('完成这一步', { exact: true }).click()
    await expect(page.locator('.task--next .subtitle')).not.toHaveText(title)
  }
  await expect(page.getByText(/当前第 2\/2 轮/)).toBeVisible()
  const cycleTwoTasks = page.locator('.task--next')
  await cycleTwoTasks.locator('textarea').fill('第二轮重新说明证据链与不确定性。')
  await expect(cycleTwoTasks.locator('uni-button.primary')).not.toHaveAttribute('disabled')
  const discussionTitle = await cycleTwoTasks.locator('.subtitle').innerText()
  await cycleTwoTasks.getByText('完成这一步', { exact: true }).click()
  await expect(page.locator('.task--next .subtitle')).not.toHaveText(discussionTitle)
  await page.locator('.task--next uni-label').nth(0).click()
  await expect(page.locator('.task--next uni-button.primary')).not.toHaveAttribute('disabled')
  const reviewTitle = await page.locator('.task--next .subtitle').innerText()
  await page.locator('.task--next').getByText('完成这一步', { exact: true }).click()
  await expect(page.locator('.task--next .subtitle')).not.toHaveText(reviewTitle)
  await page.locator('.task--next uni-label').nth(1).click()
  await expect(page.locator('.task--next uni-button.primary')).not.toHaveAttribute('disabled')
  await page.locator('.task--next').getByText('完成这一步', { exact: true }).click()

  await expect(page.getByText('需继续巩固', { exact: true })).toBeVisible()
  await expect(page.getByText('自动轮次已结束，仍有目标需线下支持。', { exact: true })).toBeVisible()
  await page.locator('.student-nav__item').filter({ hasText: '学情' }).click()
  await expect(page.getByText('需线下支持', { exact: true }).first()).toBeVisible()
  await page.locator('.report-row').first().click()
  await expect(page.getByText('目标改善对照', { exact: true })).toBeVisible()
  await expect(page.getByText('自动轮次结束，仍需线下支持', { exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByText('当前重点', { exact: true })).toBeVisible()
  await page.locator('.student-nav__item').filter({ hasText: '答疑' }).click()
  await page.getByText('退出', { exact: true }).click()
  await page.locator('.role-button.teacher').click()
  await expect(page.getByText(/自动轮次已结束，需线下支持/)).toBeVisible()
  await expect(page.getByRole('button', { name: '确认已改善' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '继续巩固' })).toHaveCount(0)
})
